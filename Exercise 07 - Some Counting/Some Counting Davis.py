#Some Counting
#1. Loop that counts from 0 to 50 in the increments of 1
print("Counting from 0 to 50:-")
for d in range(0,51,1):
    print(d)
print('-----------------------------------------------------------------') #For separation 
#2. Loop that counts down from 50 to 0 in the decrements of 1
print("Counting down from 50 to 0:-")
for a in range(50,-1,-1):
    print(a)
print('-----------------------------------------------------------------') #For separation
#3. Loop that counts from 30 to 50 in the increments of 1
print("Counting from 30 to 50:-")
